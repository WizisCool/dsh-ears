export function fallbackTranslate(key: string, params?: Record<string, unknown>): string {
  const template = localeEn[key as keyof typeof localeEn] ?? key
  return params === undefined ? template : template.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match)
}

